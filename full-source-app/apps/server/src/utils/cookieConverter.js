import fs from 'fs';
import path from 'path';
import { logger } from '../lib/logger.js';
/**
 * Convert JSON cookies to Netscape format string
 * Format: domain_flag_path_secure_expiration_name_value
 */
export function jsonToNetscape(cookies) {
    if (!cookies || !Array.isArray(cookies)) {
        return '';
    }
    let output = '# Netscape HTTP Cookie File\n# This file is generated by UpProject. Do not edit.\n\n';
    for (const cookie of cookies) {
        const domain = cookie.domain;
        if (!domain)
            continue;
        // TRUE/FALSE for domain matching all subdomains
        const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
        // Path
        const path = cookie.path || '/';
        // Secure connection only
        const secure = cookie.secure ? 'TRUE' : 'FALSE';
        // Expiration
        // If session cookie (no expires), set to 0 or far future? Netscape usually 0 for session.
        // However, yt-dlp might ignore 0 expiry.
        // If expires is missing, use session end (0).
        const expiration = cookie.expires ? Math.floor(cookie.expires) : 0;
        output += `${domain}\t${flag}\t${path}\t${secure}\t${expiration}\t${cookie.name}\t${cookie.value}\n`;
    }
    return output;
}
/**
 * Write JSON cookies to a temporary Netscape format file
 * Returns the path to the temporary file
 */
export function writeCookiesToTempFile(cookiesJson) {
    try {
        const cookies = JSON.parse(cookiesJson);
        let netscapeContent = jsonToNetscape(cookies);
        // Ensure temp dir exists
        const tempDir = path.join(process.cwd(), 'temp', 'cookies');
        if (!fs.existsSync(tempDir)) {
            fs.mkdirSync(tempDir, { recursive: true });
        }
        const tempPath = path.join(tempDir, `cookies_${Date.now()}_${Math.random().toString(36).substring(7)}.txt`);
        fs.writeFileSync(tempPath, netscapeContent);
        return tempPath;
    }
    catch (error) {
        logger.error('Failed to write cookies to temp file:', error);
        return '';
    }
}
